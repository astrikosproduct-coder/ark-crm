"""
Write backend/data/locations.json — every country, its Region, and its states.

    pip install pycountry          # development only; production never runs this
    python tools/build_locations.py

The file it writes is COMMITTED and is what release_1_1_location_metadata.py
loads into the register, so production needs no extra package. Re-run this
only to take a newer ISO list.

SOURCES
-------
Countries: ISO 3166-1, 249 of them, keyed by the two-letter code (IN, AE, US).
States:    ISO 3166-2 FIRST-LEVEL subdivisions only (parent_code empty) — the
           36 states and union territories of India, the 7 emirates, the 50
           states of the USA and its districts and territories. Second-level
           units (France's departments under its regions, England's counties)
           are left out: a dropdown of a few thousand is already the ceiling.
Regions:   ARK's five — India, MEA, APAC, Americas, Europe — assigned below
           from the UN M49 grouping, with ARK's reading of it:
             India     India only (it is both a Region and a Country).
             MEA       Africa, and Western Asia with Iran; not Cyprus.
             Europe    Europe, with Cyprus.
             Americas  North, Central and South America and the Caribbean.
             APAC      the rest of Asia, and Oceania.
           Antarctica is in no Region. The mapping is data: it is changed in
           Setup's Map Dependency Fields (Phase 2), not here.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pycountry

OUT = Path(__file__).resolve().parent.parent / "data" / "locations.json"

INDIA = {"IN"}

AFRICA = set(
    "AO BF BI BJ BW CD CF CG CI CM CV DJ DZ EG EH ER ET GA GH GM GN GQ GW KE KM LR LS LY MA MG ML MR MU MW MZ "
    "NA NE NG RE RW SC SD SH SL SN SO SS ST SZ TD TG TN TZ UG YT ZA ZM ZW IO TF".split()
)
MIDDLE_EAST = set("AE AM AZ BH GE IL IQ IR JO KW LB OM PS QA SA SY TR YE".split())

EUROPE = set(
    "AD AL AT AX BA BE BG BY CH CY CZ DE DK EE ES FI FO FR GB GG GI GR HR HU IE IM IS IT JE LI LT LU LV MC MD "
    "ME MK MT NL NO PL PT RO RS RU SE SI SJ SK SM UA VA".split()
)

AMERICAS = set(
    "AG AI AR AW BB BL BM BO BQ BR BS BV BZ CA CL CO CR CU CW DM DO EC FK GD GF GL GP GS GT GY HN HT JM KN KY "
    "LC MF MQ MS MX NI PA PE PM PR PY SR SV SX TC TT UM US UY VC VE VG VI".split()
)

NO_REGION = {"AQ"}


def country_label(c) -> str:
    """The name people use: 'Iran', not 'Iran, Islamic Republic of'."""
    return getattr(c, "common_name", None) or c.name


def region_of(code: str) -> str | None:
    if code in NO_REGION:
        return None
    if code in INDIA:
        return "INDIA"
    if code in AFRICA or code in MIDDLE_EAST:
        return "MEA"
    if code in EUROPE:
        return "EUROPE"
    if code in AMERICAS:
        return "AMERICAS"
    return "APAC"


def main() -> int:
    countries = sorted(pycountry.countries, key=lambda c: country_label(c))
    known = {c.alpha_2 for c in countries}
    for name, group in (("AFRICA", AFRICA), ("MIDDLE_EAST", MIDDLE_EAST), ("EUROPE", EUROPE), ("AMERICAS", AMERICAS)):
        unknown = group - known
        if unknown:
            print(f"{name} names codes ISO does not have: {sorted(unknown)}")
            return 1

    regions: dict[str, list[str]] = {}
    for c in countries:
        region = region_of(c.alpha_2)
        if region:
            regions.setdefault(region, []).append(c.alpha_2)

    states: dict[str, list[dict[str, str]]] = {}
    for s in pycountry.subdivisions:
        if s.parent_code is None:
            states.setdefault(s.country_code, []).append({"key": s.code, "label": s.name})
    for rows in states.values():
        rows.sort(key=lambda r: r["label"])

    document = {
        "$note": (
            "Generated by backend/tools/build_locations.py from ISO 3166-1 and the first level of "
            "ISO 3166-2 (pycountry " + getattr(pycountry, "__version__", "?") + "). Regions are ARK's "
            "five, assigned in that script. Loaded into the register by release_1_1_location_metadata.py."
        ),
        "regions": regions,
        "countries": [{"key": c.alpha_2, "label": country_label(c)} for c in countries],
        # Other names a person may have typed in the old free-text Country, for
        # converting it: ISO's name and official name, and the 3-letter code.
        "aliases": {
            c.alpha_2: sorted(
                {n for n in (c.name, getattr(c, "official_name", None), c.alpha_3) if n and n != country_label(c)}
            )
            for c in countries
        },
        "states": dict(sorted(states.items())),
    }
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(document, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")

    print(f"wrote {OUT}")
    print(f"  {len(document['countries'])} countries, {sum(len(v) for v in states.values())} states "
          f"in {len(states)} countries")
    for region, codes in regions.items():
        print(f"  {region:9} {len(codes)} countries")
    print("  APAC:", " ".join(regions.get("APAC", [])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
